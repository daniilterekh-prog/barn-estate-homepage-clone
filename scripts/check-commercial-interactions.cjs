const path = require('node:path');
const assert = require('node:assert/strict');
const toolkit = process.env.WEB_CAPTURE_TOOLKIT || '/home/daniil/Documents/Codex/2026-10-11/firecrawl/work/web-capture-toolkit';
const { chromium } = require(path.join(toolkit,'node_modules/playwright'));

(async()=>{
  const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.goto('file://'+path.resolve(__dirname,'../kommercheskaya-nedvizhimost/index.html'),{waitUntil:'load'});
  await page.evaluate(()=>document.fonts.ready);
  await page.locator('.site-header__icon-btn').click();
  await assert.doesNotReject(()=>page.getByRole('dialog',{name:'Меню сайта'}).waitFor({state:'visible'}));
  await page.keyboard.press('Escape');
  await page.getByRole('dialog',{name:'Меню сайта'}).waitFor({state:'detached'});
  await page.locator('[data-commercial-filters="hero"]').click();
  await page.getByRole('dialog',{name:'Фильтры',exact:true}).waitFor({state:'visible'});
  await page.keyboard.press('Escape');
  await page.locator('.apartment-card__call-btn').first().click();
  await page.locator('.feedback-modal').waitFor({state:'visible'});
  await page.locator('.feedback-modal__submit').click();
  assert.equal(await page.locator('.feedback-modal input:invalid').count()>0,true);
  assert.equal(await page.locator('.source-form-status').count(),0);
  await page.keyboard.press('Escape');
  const question=page.locator('.catalog-faq__question').first();
  await question.click();assert.equal(await question.getAttribute('aria-expanded'),'true');
  await question.click();assert.equal(await question.getAttribute('aria-expanded'),'false');
  const intro=page.locator('.catalog-intro__toggle');
  await intro.click();assert.equal(await intro.getAttribute('aria-expanded'),'true');
  await intro.click();assert.equal(await intro.getAttribute('aria-expanded'),'false');
  const favorite=page.locator('.apartment-card__favorite').first();
  await favorite.click();assert.equal(await favorite.getAttribute('aria-pressed'),'true');
  await page.locator('.catalog-grid__sort-select').selectOption('price_desc');
  const prices=await page.locator('.catalog-grid .apartment-card__price').allTextContents();
  const values=prices.map(value=>Number(value.replace(/[^\d,.]/g,'').replace(',','.')));
  assert.deepEqual(values,[...values].sort((a,b)=>b-a));
  assert.equal(await page.locator('.catalog-grid__list>.catalog-grid__item').count(),12);
  const before=await page.locator('.news-section .splide__list').evaluate(e=>e.style.transform);
  await page.locator('.news-section__nav-btn').nth(1).click();
  const after=await page.locator('.news-section .splide__list').evaluate(e=>e.style.transform);
  assert.notEqual(before,after);
  const linkProblems=await page.locator('a').evaluateAll(anchors=>anchors.filter(a=>!a.getAttribute('href')||a.getAttribute('href')==='#').map(a=>a.textContent.trim()));
  assert.deepEqual(linkProblems,[]);
  await page.setViewportSize({width:390,height:900});
  assert.equal(await page.locator('.catalog-grid__item:visible').count(),5);
  assert.equal(await page.locator('.news-section .splide__pagination').isVisible(),true);
  await page.locator('.news-section .splide__pagination__page').nth(2).click();
  assert.equal(await page.locator('.news-section .splide__pagination__page').nth(2).getAttribute('aria-selected'),'true');
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('PASS: menu, filters, callback validation, FAQ, read-more, favorites, sorting, slider, links, mobile cards and pagination; no browser exceptions.');
})().catch(error=>{console.error(error);process.exitCode=1});
