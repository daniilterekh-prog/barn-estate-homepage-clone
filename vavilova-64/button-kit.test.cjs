const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8')
test('location retains only its original consultation action', () => {
  const section = read('index.html').match(/<section[^>]*id="location"[\s\S]*?<\/section>/)[0]
  assert.equal((section.match(/<button[^>]*detail-location__action/g) || []).length, 1)
  assert.ok(section.includes('detail-location__action--primary'))
  assert.ok(!section.includes('detail-location__action--secondary'))
  assert.ok(read('reference-interactions.js').includes('.detail-location__action--primary'))
})
test('hero height follows ambassadors breakpoints, not viewport height', () => {
  const css = read('architecture-hero.css')
  assert.doesNotMatch(css, /\b(?:\d+(?:\.\d+)?)(?:s|d|l)?vh\b/)
  for (const height of [900,1040,640,560,520]) assert.ok(css.includes(`min-height: ${height}px`))
  assert.match(css, /height: auto; min-height: inherit/)
})
test('hero arrows have no motion or transform transition', () => {
  const css = read('architecture-hero.css')
  assert.doesNotMatch(css, /transition:\s*transform/)
  assert.doesNotMatch(css, /transform:\s*translate/)
})
test('hero uses semantic 24px kit icons instead of custom arrows', () => {
  const js = read('architecture-hero.js')
  assert.match(js, /0 0 24 24/)
  assert.match(js, /m20 20-3.5-3.5/)
  assert.doesNotMatch(js, /M3 13 13 3M5 3h8v8/)
})
test('both hero actions share the ActionButton contract', () => {
  const css = read('button-kit.css')
  assert.match(css, /detail-hero__actions \.detail-hero__button \{/)
  assert.doesNotMatch(css, /Presentation remains the approved text CTA/)
  assert.match(css, /min-width: 300px/)
})
test('contact selector removes stale snapshot tab semantics', () => {
  const js = read('reference-interactions.js')
  assert.ok(js.includes("button.removeAttribute('aria-selected')"))
  assert.ok(js.includes("button.removeAttribute('role')"))
  assert.ok(js.includes("setAttribute('role', 'group')"))
})
